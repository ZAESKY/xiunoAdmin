<?php

namespace app\pay\library\wxpay;

use app\pay\service\CommonService;
use think\facade\Db;

class PayNotifyCallBack extends WxPayNotify
{
    public function initialize()
    {
        parent::initialize(); // TODO: Change the autogenerated stub
        $this->service = new CommonService();
    }
    //查询订单
    public function Queryorder($transaction_id)
    {
        $input = new WxPayOrderQuery();
        $input->SetTransaction_id($transaction_id);
        $result = WxPayApi::orderQuery($input);
        //Log::DEBUG("query:" . json_encode($result));
        if(is_array($result) && array_key_exists("return_code", $result)
            && array_key_exists("result_code", $result)
            && $result["return_code"] == "SUCCESS"
            && $result["result_code"] == "SUCCESS")
        {
            return true;
        }
        return false;
    }

    //重写回调处理函数
    public function NotifyProcess($data, &$msg)
    {
        //file_put_contents('log.txt',"call back:" . json_encode($data));
        $notfiyOutput = array();

        if(!is_array($data) || !array_key_exists("transaction_id", $data)){
            $msg = "输入参数不正确";
            return false;
        }
        //查询订单，判断订单真实性
        if(!$this->Queryorder($data["transaction_id"])){
            $msg = "订单查询失败";
            return false;
        }
        if($data['return_code'] == 'SUCCESS'){
            if($data['result_code'] == 'SUCCESS'){
                $out_trade_no = $data['out_trade_no'];
                $srow = Db::name('pay')->where('trade_no', $out_trade_no)->find();
                if($srow['status'] == 0){
                    $result = Db::name('pay')->where('trade_no', $out_trade_no)->update(['status' => 1]);
                    if($result){
                        Db::name('pay')->where('trade_no', $out_trade_no)->update(['endtime' => datetime(), 'api_trade_no' => $data['transaction_id']]);
                        $this->service->processOrder($srow);
                    }
                    $msg='OK';
                    return true;
                }else{
                    $msg='该订单已经处理';
                    return true;
                }
            }else{
                $msg='['.$data['err_code'].']'.$data['err_code_des'];
                return false;
            }
        }else{
            $msg='['.$data['return_code'].']'.$data['return_msg'];
            return false;
        }
        return true;
    }
}